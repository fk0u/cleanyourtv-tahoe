#!/usr/bin/env python3
"""Fetch Lucide icons (ISC licence) and convert them to Android VectorDrawables.

usage: tools/lucide.py            -> writes launcher/src/main/res/drawable/ic_<name>.xml for ICONS
Lucide icons are 24x24, stroke 2, round caps/joins; we keep that and tint at runtime."""
import pathlib, re, sys, urllib.request
import xml.etree.ElementTree as ET

VERSION = "0.460.0"
ICONS = """sun moon cloud cloud-sun cloud-moon cloud-fog cloud-rain cloud-drizzle cloud-lightning snowflake
sparkles smartphone settings house wifi bluetooth image volume-2 play pause skip-forward skip-back gamepad-2
bell bell-off chevron-left calendar moon-star lightbulb power fan thermometer info trash-2 pin pin-off
arrow-left-right music mic clock user users layout-grid tv""".split()
OUT = pathlib.Path(__file__).resolve().parent.parent / "launcher/src/main/res/drawable"


def num(v): return float(v or 0)
def fmt(x): return ("%.3f" % x).rstrip("0").rstrip(".")


def to_path(el):
    tag = el.tag.split("}")[-1]
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = num(a.get("cx")), num(a.get("cy")), num(a["r"])
        return f"M{fmt(cx - r)},{fmt(cy)} a{fmt(r)},{fmt(r)} 0 1,0 {fmt(2 * r)},0 a{fmt(r)},{fmt(r)} 0 1,0 {fmt(-2 * r)},0"
    if tag == "ellipse":
        cx, cy, rx, ry = num(a.get("cx")), num(a.get("cy")), num(a["rx"]), num(a["ry"])
        return f"M{fmt(cx - rx)},{fmt(cy)} a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(2 * rx)},0 a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(-2 * rx)},0"
    if tag == "line":
        return f"M{a['x1']},{a['y1']} L{a['x2']},{a['y2']}"
    if tag in ("polyline", "polygon"):
        pts = re.findall(r"-?[\d.]+", a["points"])
        pairs = [f"{pts[i]},{pts[i + 1]}" for i in range(0, len(pts), 2)]
        return "M" + " L".join(pairs) + (" Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y, w, h = num(a.get("x")), num(a.get("y")), num(a["width"]), num(a["height"])
        rx = num(a.get("rx", a.get("ry"))); ry = num(a.get("ry", a.get("rx")))
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if rx == 0:
            return f"M{fmt(x)},{fmt(y)} h{fmt(w)} v{fmt(h)} h{fmt(-w)} Z"
        return (f"M{fmt(x + rx)},{fmt(y)} h{fmt(w - 2 * rx)} a{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(rx)},{fmt(ry)} v{fmt(h - 2 * ry)} "
                f"a{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(-rx)},{fmt(ry)} h{fmt(-(w - 2 * rx))} a{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(-rx)},{fmt(-ry)} "
                f"v{fmt(-(h - 2 * ry))} a{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(rx)},{fmt(-ry)} Z")
    raise ValueError("unsupported element " + tag)


def convert(name, svg):
    root = ET.fromstring(svg)
    paths = []
    for el in root.iter():
        if el is root or el.tag.split("}")[-1] in ("title", "desc", "g"):
            continue
        paths.append(to_path(el))
    body = "\n".join(
        f'    <path android:pathData="{p}" android:strokeColor="#FFFFFFFF" android:strokeWidth="2" '
        f'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />' for p in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Lucide "{name}" v{VERSION} (ISC licence), generated by tools/lucide.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp"\n'
            '    android:viewportWidth="24" android:viewportHeight="24">\n' + body + "\n</vector>\n")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name in ICONS:
        url = f"https://cdn.jsdelivr.net/npm/lucide-static@{VERSION}/icons/{name}.svg"
        svg = urllib.request.urlopen(url, timeout=15).read().decode()
        (OUT / f"ic_{name.replace('-', '_')}.xml").write_text(convert(name, svg))
        print("ic_" + name.replace("-", "_"))


if __name__ == "__main__":
    # self-check of the shape converters
    assert to_path(ET.fromstring('<line x1="1" y1="2" x2="3" y2="4"/>')) == "M1,2 L3,4"
    assert to_path(ET.fromstring('<polygon points="1 2 3 4 5 6"/>')) == "M1,2 L3,4 L5,6 Z"
    assert to_path(ET.fromstring('<circle cx="12" cy="12" r="4"/>')).startswith("M8,12 a4,4")
    sys.exit(main())
