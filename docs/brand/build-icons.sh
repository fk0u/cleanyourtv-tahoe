#!/bin/sh
# Regenerates every app icon / banner from the one mark geometry below. Needs rsvg-convert + iconutil (macOS) + python3 PIL.
# Run from the repo root: sh docs/brand/build-icons.sh
set -e
cd "$(dirname "$0")/../.."
B=docs/brand
# Mark on a 24-unit grid: screen (2,4)-(22,20), stand, two peaks, the lake wave, the live light.
SCREEN="M6.5,4 h11 a4.5,4.5 0 0 1 4.5,4.5 v7 a4.5,4.5 0 0 1 -4.5,4.5 h-11 a4.5,4.5 0 0 1 -4.5,-4.5 v-7 a4.5,4.5 0 0 1 4.5,-4.5 z M9,22.5 h6"
PEAKS="M5.8,13.6 L9.4,8.8 L11.9,11.6 L14.4,8.4 L18.2,13.6"
WAVE="M6.2,16.6 q1.45,-1.1 2.9,0 t2.9,0 t2.9,0 t2.9,0"
mark() { # $1 stroke, $2 dot, $3 transform
  echo "<g transform=\"$3\" fill=\"none\" stroke=\"$1\" stroke-width=\"2\" stroke-linecap=\"round\" stroke-linejoin=\"round\"><path d=\"$SCREEN\"/><path d=\"$PEAKS\"/><path d=\"$WAVE\"/><circle cx=\"18\" cy=\"7.6\" r=\"1.4\" fill=\"$2\" stroke=\"none\"/></g>"; }
GRAD='<linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#64D2FF"/><stop offset="0.55" stop-color="#1F3BD1"/><stop offset="1" stop-color="#0A1A7A"/></linearGradient>'
cat > $B/logo-mark.svg <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="240" height="240"><title>Tahoe TV mark</title>$(mark "#F5F5F7" "#64D2FF" "")</svg>
EOF
cat > $B/logo-mark-dark.svg <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="240" height="240"><title>Tahoe TV mark (on light)</title>$(mark "#0E0F13" "#2EA8E0" "")</svg>
EOF
cat > $B/logo-app-icon.svg <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024"><defs>$GRAD</defs><rect x="64" y="64" width="896" height="896" rx="210" fill="url(#g)"/>$(mark "#FFFFFF" "#9BE3FF" "translate(212 200) scale(25)")</svg>
EOF
cat > $B/logo-lockup.svg <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 380 96" width="760" height="192"><rect width="380" height="96" rx="20" fill="#0E0F13"/>$(mark "#F5F5F7" "#64D2FF" "translate(18 12) scale(3)")<text x="104" y="61" fill="#F5F5F7" font-family="Outfit" font-size="40" font-weight="700" letter-spacing="-0.5">Tahoe <tspan fill="#64D2FF">TV</tspan></text></svg>
EOF
cat > $B/tv-banner.svg <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 180" width="640" height="360"><defs>$GRAD</defs><rect width="320" height="180" fill="url(#g)"/>$(mark "#FFFFFF" "#9BE3FF" "translate(28 58) scale(2.7)")<text x="104" y="103" fill="#FFFFFF" font-family="Outfit" font-size="40" font-weight="700" letter-spacing="-0.5">Tahoe TV</text></svg>
EOF
# Android vector drawables (adaptive icon 108dp canvas, mark inside the 66dp safe zone).
for app in companion launcher; do
  D=$app/src/main/res/drawable; mkdir -p $D $app/src/main/res/mipmap-anydpi-v26
  vec() { cat <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by docs/brand/build-icons.sh: the Tahoe TV mark. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="25.2" android:translateY="24" android:scaleX="2.4" android:scaleY="2.4">
        <path android:strokeColor="$1" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="$SCREEN $PEAKS"/>
        <path android:strokeColor="$1" android:strokeWidth="2" android:strokeLineCap="round" android:pathData="M6.2,16.6 q1.45,-1.1 2.9,0 q1.45,1.1 2.9,0 q1.45,-1.1 2.9,0 q1.45,1.1 2.9,0"/>
        <path android:fillColor="$2" android:pathData="M16.6,7.6 a1.4,1.4 0 1 0 2.8,0 a1.4,1.4 0 1 0 -2.8,0 z"/>
    </group>
</vector>
EOF
  }
  vec "#FFFFFFFF" "#FF9BE3FF" > $D/ic_launcher_fg.xml
  vec "#FFFFFFFF" "#FFFFFFFF" > $D/ic_launcher_mono.xml
  cat > $D/ic_launcher_bg.xml <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by docs/brand/build-icons.sh: brand gradient Cyan → Lake → Lake Deep. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0 h108 v108 h-108 z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="#FF64D2FF"/>
                <item android:offset="0.55" android:color="#FF1F3BD1"/>
                <item android:offset="1" android:color="#FF0A1A7A"/>
            </gradient>
        </aapt:attr>
    </path>
</vector>
EOF
  cat > $app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_bg" />
    <foreground android:drawable="@drawable/ic_launcher_fg" />
    <monochrome android:drawable="@drawable/ic_launcher_mono" />
</adaptive-icon>
EOF
done
# Rasters. Fonts: rsvg finds Outfit if installed; otherwise copy launcher/src/main/assets/Outfit.ttf to ~/Library/Fonts.
mkdir -p launcher/src/main/res/drawable-xhdpi
rsvg-convert -w 640 -h 360 $B/tv-banner.svg -o launcher/src/main/res/drawable-xhdpi/banner.png
rsvg-convert -w 1024 -h 1024 $B/logo-app-icon.svg -o $B/app-icon-1024.png
cp $B/app-icon-1024.png desktop/src/main/resources/icon.png
python3 -c "from PIL import Image; Image.open('$B/app-icon-1024.png').save('desktop/icons/tahoe.ico',sizes=[(16,16),(32,32),(48,48),(64,64),(128,128),(256,256)])"
I=$(mktemp -d)/tahoe.iconset; mkdir -p $I
for s in 16 32 128 256 512; do rsvg-convert -w $s -h $s $B/logo-app-icon.svg -o $I/icon_${s}x${s}.png; rsvg-convert -w $((s*2)) -h $((s*2)) $B/logo-app-icon.svg -o $I/icon_${s}x${s}@2x.png; done
iconutil -c icns $I -o desktop/icons/tahoe.icns
echo "icons done"
