    internal val TABLES = mapOf("en" to EN, "id" to ID, "zh" to ZH)

    @JvmStatic
    fun table(lang: String): Map<String, String> = when (lang.lowercase(Locale.US)) {
        "en" -> EN
        "zh" -> ZH
        else -> ID
    }

    @JvmStatic
    @JvmOverloads
    fun get(lang: String, key: String, vararg args: Any?): String {
        val template = table(lang)[key] ?: ID[key] ?: key
        if (args.isEmpty()) return template
        return runCatching { String.format(Locale.US, template, *args) }.getOrDefault(template)
    }

    @JvmStatic
    fun greeting(lang: String, hour: Int): String = when (hour) {
        in 4..10 -> get(lang, "greet.morning")
        in 11..14 -> get(lang, "greet.day")
        in 15..17 -> get(lang, "greet.evening")
        else -> get(lang, "greet.night")
    }
